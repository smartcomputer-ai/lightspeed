for (const entry of methods) {
  if (!entry.access || typeof entry.access.kind !== "string") {
    throw new Error(`method ${entry.method} is missing access classification`);
  }
  if (typeof entry.summary !== "string" || entry.summary.trim().length === 0) {
    throw new Error(`method ${entry.method} is missing summary documentation`);
  }
  if (
    typeof entry.description !== "string" ||
    entry.description.trim().length === 0
  ) {
    throw new Error(
      `method ${entry.method} is missing description documentation`,
    );
  }
}

function typeNameFromRef(entry, method, side) {
  const ref = entry?.schema?.$ref;
  const prefix = "api.schema.json#/definitions/";
  if (typeof ref !== "string" || !ref.startsWith(prefix)) {
    throw new Error(`method ${method} ${side} schema is not a definitions ref`);
  }
  return ref.slice(prefix.length);
}

function q(value) {
  return JSON.stringify(value);
}

function jsDoc(entry, indent = "") {
  const summary = entry.summary.replaceAll("*/", "* /");
  const description = entry.description.replaceAll("*/", "* /");
  return [
    `${indent}/**`,
    `${indent} * ${summary}`,
    `${indent} *`,
    `${indent} * ${description}`,
    `${indent} */`,
  ];
}

