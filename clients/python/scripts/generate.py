"""Generate wire types, client methods and workflow contract data from the checked-in exports."""

import argparse
import ast
import json
import pprint
import re
import subprocess
import sys
import textwrap
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
CLIENTS = PACKAGE.parent
CONTRACT = CLIENTS.parent / "crates/api/contract"
WORKFLOW_CONTRACT = CLIENTS.parent / "crates/temporal-workflow/contract"
OUTPUT = PACKAGE / "src/lightspeed_ai"
BANNER = "# Generated by clients/python/scripts/generate.py. Do not edit.\n"


def snake_case(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def reference(schema: dict) -> str:
    return schema["$ref"].removeprefix("#/definitions/")


def model_types(schema: Path) -> str:
    return subprocess.check_output(
        [
            sys.executable, "-m", "datamodel_code_generator",
            "--input", schema.name, "--input-file-type", "jsonschema",
            # Aliases are written as assignments, not 3.12 `type` statements, which
            # libraries that decode values from type hints, such as Temporal's data
            # converter, do not resolve.
            "--output-model-type", "typing.TypedDict", "--target-python-version", "3.11",
            "--disable-timestamp", "--enum-field-as-literal", "all",
            "--formatters", "builtin", "--no-use-closed-typed-dict",
            # Carry the contract's descriptions, and name each union variant after
            # its tag (`SessionEventKindViewRunFailed`) so adding a variant does
            # not renumber the ones after it.
            "--use-schema-description", "--use-field-description",
            "--infer-union-variant-names",
        ],
        cwd=schema.parent,
        text=True,
    )


def render_workflow_manifest() -> str:
    manifest = json.loads((WORKFLOW_CONTRACT / "workflow.json").read_text())
    return "\n".join([
        BANNER.rstrip(),
        "from typing import Any",
        "",
        "WORKFLOW_CONTRACT_MANIFEST: dict[str, Any] = (",
        pprint.pformat(manifest, width=100, sort_dicts=False),
        ")",
        "",
    ])


def helper_inventory() -> list:
    return json.loads(subprocess.check_output(
        [
            "node", "--input-type=module", "-e",
            "import { HELPERS } from './scripts/helpers.mjs'; console.log(JSON.stringify(HELPERS));",
        ],
        cwd=CLIENTS / "typescript",
        text=True,
    ))


class QualifyTypes(ast.NodeTransformer):
    def __init__(self, names: set[str]) -> None:
        self.names = names

    def visit_Name(self, node: ast.Name) -> ast.expr:
        if node.id in self.names:
            return ast.Attribute(value=ast.Name(id="Api", ctx=ast.Load()), attr=node.id, ctx=node.ctx)
        return node


def field_types(models: str) -> dict[str, dict[str, str]]:
    tree = ast.parse(models)
    names = {node.name for node in tree.body if isinstance(node, ast.ClassDef)}
    names.update(
        node.target.id for node in tree.body
        if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name)
    )
    qualifier = QualifyTypes(names)
    fields = {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        fields[node.name] = {}
        for field in node.body:
            if not isinstance(field, ast.AnnAssign) or not isinstance(field.target, ast.Name):
                continue
            annotation = field.annotation
            if isinstance(annotation, ast.Subscript) and ast.unparse(annotation.value) == "NotRequired":
                annotation = annotation.slice
            fields[node.name][field.target.id] = ast.unparse(qualifier.visit(annotation))
    return fields


def docstring(summary: str, description: str, arguments: dict[str, str]) -> list[str]:
    """A helper's docstring: summary, description, then the arguments the contract describes."""
    def wrap(text: str, indent: str, hanging: str = "") -> list[str]:
        text = " ".join(text.split()).replace("\\", "\\\\").replace('"""', r'\"\"\"')
        return textwrap.wrap(
            text, width=100, initial_indent=indent, subsequent_indent=indent + hanging,
            break_long_words=False, break_on_hyphens=False,
        )

    lines = ['        """' + wrap(summary, "")[0], "", *wrap(description, "        ")]
    if arguments:
        lines.extend(["", "        Args:"])
        for name, text in arguments.items():
            lines.extend(wrap(f"{name}: {text}", "            ", "    "))
    return [*lines, '        """']


def render_helper(entry: dict, name: str, targets: list[str], schema: dict, fields: dict) -> list[str]:
    method = entry["method"]
    params = reference(entry["params"]["schema"])
    result = reference(entry["result"]["schema"])
    data = reference(schema[result]["properties"]["result"])
    required = schema[params].get("required", [])
    properties = schema[params].get("properties", {})
    if any(target not in required for target in targets):
        raise ValueError(f"{method}: target IDs must be required")
    args = [f"{snake_case(target)}: {fields[params][target]}" for target in targets]
    args.append("*")
    for key in properties:
        if key in targets:
            continue
        annotation = fields[params][key]
        args.append(f"{snake_case(key)}: {annotation}" + ("" if key in required else " | Unset = UNSET"))
    args.append("headers: HeadersInput | None = None")
    described = {
        snake_case(key): properties[key]["description"]
        for key in [*targets, *(key for key in properties if key not in targets)]
        if properties[key].get("description")
    }
    lines = [
        "",
        f"    async def {name}(self, {', '.join(args)}) -> Api.{data}:",
        *docstring(entry["summary"], entry["description"], described),
        "        params: dict[str, Any] = {}",
    ]
    for key in properties:
        variable = snake_case(key)
        if key not in required:
            lines.append(f"        if {variable} is not UNSET:")
        lines.append(f"{' ' * (8 if key in required else 12)}params[{key!r}] = {variable}")
    lines.append(f"        return cast(Api.{data}, (await self._invoke({method!r}, params, headers))['result'])")
    return lines


def render_client(models: str, manifest: dict, schema: dict) -> str:
    methods = {entry["method"]: entry for entry in manifest["methods"]}
    helpers = helper_inventory()
    fields = field_types(models)
    lines = [
        BANNER.rstrip(),
        "from __future__ import annotations",
        "",
        "from typing import Any, Literal, cast, overload",
        "",
        "from . import types as Api",
        "from ._options import UNSET, HeadersInput, Unset",
        "",
        "METHODS = (",
        *(f"    {method!r}," for method in methods),
        ")",
        "",
        "NOTIFICATIONS = (",
        *(f"    {method!r}," for method in manifest.get("notifications", [])),
        ")",
        "",
        "METHOD_INFO = {",
    ]
    for method, entry in methods.items():
        info = {key: entry[key] for key in ("scope", "access", "summary", "description", "streaming", "notifications")}
        lines.append(f"    {method!r}: {info!r},")
    lines.extend(["}", "", "CLIENT_HELPERS = {"])
    lines.extend(f"    {snake_case(name)!r}: {method!r}," for method, name, *_ in helpers)
    lines.extend([
        "}", "", "", "class GeneratedClient:",
        "    async def _invoke(",
        "        self, method: str, params: dict[str, Any], headers: HeadersInput | None = None",
        "    ) -> dict[str, Any]:",
        "        raise NotImplementedError",
        "",
    ])
    for method, entry in methods.items():
        params = reference(entry["params"]["schema"])
        result = reference(entry["result"]["schema"])
        lines.extend([
            "    @overload",
            f"    async def call(self, method: Literal[{method!r}], params: Api.{params},",
            f"                   *, headers: HeadersInput | None = None) -> Api.{result}: ...",
        ])
    lines.extend([
        "",
        "    async def call(self, method: str, params: object,",
        "                   *, headers: HeadersInput | None = None) -> Any:",
        '        """Call a gateway method and return its result and notifications."""',
        "        return await self._invoke(method, cast(dict[str, Any], params), headers)",
    ])
    for method, name, *targets in helpers:
        lines.extend(render_helper(methods[method], snake_case(name), targets, schema, fields))
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed output differs")
    args = parser.parse_args()
    models = model_types(CONTRACT / "api.schema.json")
    manifest = json.loads((CONTRACT / "methods.json").read_text())
    schema = json.loads((CONTRACT / "api.schema.json").read_text())["definitions"]
    generated = {
        "types.py": BANNER + models,
        "_generated.py": render_client(models, manifest, schema),
        "workflow_types.py": BANNER + model_types(WORKFLOW_CONTRACT / "workflow.schema.json"),
        "_workflow_manifest.py": render_workflow_manifest(),
    }
    for filename, content in generated.items():
        path = OUTPUT / filename
        if args.check:
            if not path.exists() or path.read_text() != content:
                sys.exit(f"{path.name} is stale. Run python scripts/generate.py.")
        else:
            path.write_text(content)


if __name__ == "__main__":
    main()
