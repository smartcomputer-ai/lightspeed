fn print_workspace(workspace: api::VfsWorkspaceView, json: bool) -> Result<()> {
    crate::output::show(json, &workspace)
}

pub(crate) async fn create_workspace_from_snapshot(
    api: &HttpAgentApi,
    snapshot_ref: String,
) -> Result<api::VfsWorkspaceView> {
    Ok(api
        .create_vfs_workspace(api::VfsWorkspaceCreateParams {
            workspace_id: None,
            snapshot_ref: Some(snapshot_ref),
            display_name: None,
        })
        .await
        .map_err(crate::api_client::api_error)?
        .result
        .workspace)
}

pub(crate) async fn attach_workspace(
    api: &HttpAgentApi,
    session_id: String,
    mount_path: String,
    workspace_id: String,
    access: api::WorkspaceAccess,
) -> Result<api::SessionConfigPutResponse> {
    put_workspace_attachment(
        api,
        session_id,
        api::WorkspaceAttachment {
            path: mount_path,
            workspace_id: Some(workspace_id),
            snapshot_ref: None,
            access,
        },
    )
    .await
}

/// Workspace attachments are declarative session config: mount put/delete
/// are sugar that read-modify-put `features.vfs.workspaces`.
async fn put_workspace_attachment(
    api: &HttpAgentApi,
    session_id: String,
    attachment: api::WorkspaceAttachment,
) -> Result<api::SessionConfigPutResponse> {
    let session = api
        .read_session(api::SessionReadParams {
            session_id: session_id.clone(),
            run_limit: None,
        })
        .await
        .map_err(crate::api_client::api_error)?
        .result
        .session;
    let mut config = session
        .config
        .ok_or_else(|| anyhow::anyhow!("session is missing config"))?;
    let vfs = config
        .features
        .get_or_insert_with(Default::default)
        .vfs
        .get_or_insert(api::VfsFeature {
            version: api::CURRENT_FEATURE_VERSION,
            working_directory: None,
            workspaces: vec![],
            prompts: None,
            skills: None,
        });
    vfs.workspaces
        .retain(|existing| existing.path != attachment.path);
    vfs.workspaces.push(attachment);
    Ok(api
        .put_session_config(api::SessionConfigPutParams {
            session_id,
            expected_config_revision: Some(session.config_revision),
            config,
        })
        .await
        .map_err(crate::api_client::api_error)?
        .result)
}

async fn materialize(args: MaterializeArgs) -> Result<()> {
    let api = HttpAgentApi::new(args.api_url);
    let summary = materialize_snapshot(&api, args.snapshot_ref, args.destination).await?;
    if args.json {
        println!("{}", serde_json::to_string_pretty(&summary)?);
        return Ok(());
    }

    println!("Snapshot ref: {}", summary.snapshot_ref);
    println!("Destination: {}", summary.destination);
    println!("Files: {}", summary.files);
    println!("Bytes: {}", summary.bytes);
    println!("Directories: {}", summary.directories);
    println!("Created directories: {}", summary.created_directories);
    println!("Written files: {}", summary.written_files);
    println!("Written bytes: {}", summary.written_bytes);
    println!("Reused files: {}", summary.reused_files);
    println!("Reused bytes: {}", summary.reused_bytes);
    println!("Downloaded blobs: {}", summary.downloaded_blobs);
    println!("Downloaded bytes: {}", summary.downloaded_bytes);
    Ok(())
}

fn snapshot_options(args: &SnapshotArgs) -> SnapshotUploadOptions {
    SnapshotUploadOptions {
        limits: vfs::VfsSnapshotLimits::new(
            args.max_files,
            args.max_total_bytes,
            args.max_file_bytes,
            args.max_depth,
        ),
        max_put_many_batch_bytes: args.put_batch_bytes,
        max_put_many_batch_files: args.put_batch_files,
        max_has_many_refs: args.has_batch_refs,
    }
}
