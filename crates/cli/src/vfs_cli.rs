struct WorkspaceDeleteArgs {
    /// JSON-RPC agent API URL.
    #[arg(skip)]
    api_url: String,
    /// Emit the deleted workspace summary as JSON.
    #[arg(long)]
    json: bool,
    /// Workspace id to delete.
    workspace_id: String,
}

#[derive(ValueEnum, Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum WorkspaceAccessArg {
    Read,
    Edit,
}

impl From<WorkspaceAccessArg> for api::WorkspaceAccess {
    fn from(access: WorkspaceAccessArg) -> Self {
        match access {
            WorkspaceAccessArg::Read => api::WorkspaceAccess::Read,
            WorkspaceAccessArg::Edit => api::WorkspaceAccess::Edit,
        }
    }
}

async fn snapshot(args: SnapshotArgs) -> Result<()> {
    let options = snapshot_options(&args);
    let api = HttpAgentApi::new(args.api_url);
    let summary = upload_snapshot_directory(&api, args.directory, options).await?;
    if args.json {
        println!("{}", serde_json::to_string_pretty(&summary)?);
        return Ok(());
    }

    println!("Snapshot ref: {}", summary.snapshot_ref);
    println!("Files: {}", summary.files);
    println!("Bytes: {}", summary.bytes);
    println!("Uploaded blobs: {}", summary.uploaded_blobs);
    println!("Uploaded bytes: {}", summary.uploaded_bytes);
    println!("Reused blobs: {}", summary.reused_blobs);
    println!("Reused bytes: {}", summary.reused_bytes);
    if summary.skipped_paths > 0 {
        println!("Skipped paths: {}", summary.skipped_paths);
        for warning in summary.warnings {
            println!("Warning: {}: {}", warning.path, warning.message);
        }
    }
    Ok(())
}

pub(crate) async fn workspace(args: WorkspaceArgs) -> Result<()> {
    match args.command {
        WorkspaceCommand::Create(args) => workspace_create(args).await,
        WorkspaceCommand::Read(args) => workspace_read(args).await,
        WorkspaceCommand::List(args) => workspace_list(args).await,
        WorkspaceCommand::Update(args) => workspace_update(args).await,
        WorkspaceCommand::Delete(args) => workspace_delete(args).await,
        WorkspaceCommand::Snapshot(args) => match args.command {
            SnapshotCommand::Upload(args) => snapshot(args).await,
            SnapshotCommand::Download(args) => materialize(args).await,
        },
    }
}

async fn workspace_create(args: WorkspaceCreateArgs) -> Result<()> {
    let api = HttpAgentApi::new(args.api_url);
    let response = api
        .create_vfs_workspace(api::VfsWorkspaceCreateParams {
            workspace_id: args.workspace_id,
            snapshot_ref: args.snapshot_ref,
            display_name: args.display_name,
        })
        .await
        .map_err(crate::api_client::api_error)?
        .result;
    print_workspace(response.workspace, args.json)
}

async fn workspace_list(args: WorkspaceListArgs) -> Result<()> {
    let api = HttpAgentApi::new(args.api_url);
    let response = api
        .list_vfs_workspaces(api::VfsWorkspaceListParams {})
        .await
        .map_err(crate::api_client::api_error)?
        .result;
    if args.json {
        println!("{}", serde_json::to_string_pretty(&response.workspaces)?);
        return Ok(());
    }
    crate::output::table(
        &response.workspaces,
        &[
            ("workspaceId", "ID"),
            ("displayName", "NAME"),
            ("files", "FILES"),
            ("bytes", "BYTES"),
            ("revision", "REVISION"),
        ],
        "No workspaces found.",
    )
}

