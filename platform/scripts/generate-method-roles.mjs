// Regenerates server/src/routes/method-roles.ts from the core method
// manifest: the least member role each universe method needs, the methods
// that act on one session, and the methods no member calls through a
// universe (deployment and service methods). Run after core methods change:
//
//   node platform/scripts/generate-method-roles.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const manifestPath = path.resolve(here, "../../crates/api/contract/methods.json");
const outPath = path.resolve(here, "../server/src/routes/method-roles.ts");

const { methods } = JSON.parse(readFileSync(manifestPath, "utf8"));
const roles = [];
const targets = [];
const unmembered = [];
for (const spec of [...methods].sort((a, b) => a.method.localeCompare(b.method))) {
  if (spec.role) roles.push(`  ${JSON.stringify(spec.method)}: ${JSON.stringify(spec.role)},`);
  else unmembered.push(`  ${JSON.stringify(spec.method)},`);
  if (spec.target === "sessionId") targets.push(`  ${JSON.stringify(spec.method)},`);
}

writeFileSync(outPath, `/*
 * Generated by platform/scripts/generate-method-roles.mjs from the core
 * method manifest. Do not edit by hand.
 */
import type { UniverseRole } from "@lightspeed/platform-shared";

/** The least member role each universe method needs. */
export const METHOD_ROLES: Readonly<Record<string, UniverseRole>> = {
${roles.join("\n")}
};

/** Methods that act on one session, named by \`sessionId\`. */
export const SESSION_TARGET_METHODS: ReadonlySet<string> = new Set([
${targets.join("\n")}
]);

/** Deployment and service methods: never called on a member's behalf. */
export const UNMEMBERED_METHODS: ReadonlySet<string> = new Set([
${unmembered.join("\n")}
]);
`);
